// Learning ON vs OFF under identical initial conditions (same world seed -> same terrain, creatures, priors, personality).
// Usage: node tests/experiments/compare-learning.mjs [ticks=8000] [seeds=8]
import fs from 'node:fs';
import { World } from '../../server/src/world.js';
import { DEFAULTS, deepMerge } from '../../server/src/config.js';

const TICKS = Number(process.argv[2] ?? 8000), NSEEDS = Number(process.argv[3] ?? 8);
const A = '0x' + 'a1'.repeat(20), B = '0x' + 'b2'.repeat(20);
const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const sd = (a) => { const m = mean(a); return Math.sqrt(mean(a.map((x) => (x - m) ** 2))); };

function run(seed, learning) {
  const cfg = deepMerge(DEFAULTS, { world: { seed, learning } });
  const w = World.create(cfg);
  const cx = w.W / 2, cy = w.H / 2;
  const pos = { [A]: [cx + 5, cy], [B]: [cx - 5, cy] };
  const m = { appr: { [A]: 0, [B]: 0 }, avoid: { [A]: 0, [B]: 0 }, distA: [], distB: [], hungryTicks: 0, ctTicks: 0, firstShelter: null, rewards: [] };
  const second = TICKS / 2;
  for (let i = 1; i <= TICKS; i++) {
    if (i % 50 === 1) for (const a of [A, B]) w.visitorPresence(a, ...pos[a]);
    if (i % 200 === 10) w.visitorAction(A, 'gift_food');
    if (i % 300 === 10) w.visitorAction(B, 'startle');
    w.step();
    for (const c of w.creatures) {
      if (c.act && c.act.start.tick === w.tick && c.act.addr) (c.act.type === 'APPROACH' ? m.appr : m.avoid)[c.act.addr]++;
      if (i > second && w.isAdult(c)) { m.ctTicks++; if (c.hunger > 70) m.hungryTicks++; }
    }
    if (i > second && i % 10 === 0) {
      const ad = w.creatures.filter((c) => w.isAdult(c));
      if (ad.length) { m.distA.push(mean(ad.map((c) => Math.hypot(c.x - pos[A][0], c.y - pos[A][1])))); m.distB.push(mean(ad.map((c) => Math.hypot(c.x - pos[B][0], c.y - pos[B][1])))); }
    }
    if (m.firstShelter === null && w.totals.sheltersBuilt > 0) m.firstShelter = i;
  }
  const ratio = (o) => (o[A] + 1e-9) / (o[A] + o[B] + 1e-9);
  const ops = w.creatures.filter((c) => c.brain.wallets[A] && c.brain.wallets[B]);
  return {
    seed, learning, population: w.creatures.length, births: w.totals.births, deaths: w.totals.deaths, starved: w.totals.deathsByCause.starvation ?? 0, hurtByVisitor: w.totals.deathsByCause.visitor ?? 0,
    eaten: Math.round(w.totals.eaten), sheltersBuilt: w.totals.sheltersBuilt, firstShelterTick: m.firstShelter ?? TICKS,
    hungryFrac: m.ctTicks ? m.hungryTicks / m.ctTicks : 0,
    approachA: m.appr[A], approachB: m.appr[B], avoidA: m.avoid[A], avoidB: m.avoid[B],
    meanDistA: mean(m.distA), meanDistB: mean(m.distB),
    opinionA: ops.length ? mean(ops.map((c) => c.brain.wallets[A].v)) : null, opinionB: ops.length ? mean(ops.map((c) => c.brain.wallets[B].v)) : null,
    meanReward: mean(w.creatures.map((c) => (c.brain.rewardN ? c.brain.rewardSum / c.brain.rewardN : 0))),
  };
}
const rows = [];
for (let s = 1; s <= NSEEDS; s++) for (const l of [true, false]) rows.push(run(s, l));
const keys = ['population', 'births', 'deaths', 'starved', 'eaten', 'sheltersBuilt', 'firstShelterTick', 'hungryFrac', 'approachA', 'approachB', 'avoidA', 'avoidB', 'meanDistA', 'meanDistB', 'meanReward'];
const f = (x) => (Math.abs(x) < 10 ? x.toFixed(3) : x.toFixed(1));
let md = `# Learning ON vs OFF (measured)\n\nGenerated by \`tests/experiments/compare-learning.mjs\`: ${TICKS} ticks, seeds 1..${NSEEDS}, 24 initial creatures, default config. Each seed is run twice from the *identical* initial world (terrain, creatures, personalities, prior weights); only \`learning\` differs. Scripted visitors: wallet A leaves food every 200 ticks (helpful) at (+5,0) from the settlement centre; wallet B startles the nearest creature every 300 ticks (harmful) at (-5,0). Distances are mean adult-to-visitor distance over the second half of the run (tiles).\n\n| metric | learning ON mean ± sd | learning OFF mean ± sd | paired diff (ON−OFF) mean |\n|---|---|---|---|\n`;
for (const k of keys) {
  const on = rows.filter((r) => r.learning).map((r) => r[k]), off = rows.filter((r) => !r.learning).map((r) => r[k]);
  md += `| ${k} | ${f(mean(on))} ± ${f(sd(on))} | ${f(mean(off))} ± ${f(sd(off))} | ${f(mean(on.map((v, i) => v - off[i])))} |\n`;
}
const opn = rows.filter((r) => r.learning && r.opinionA !== null);
md += `\nMean learned creature opinion of wallet A (helpful) / B (harmful), learning ON, over seeds with creatures holding both: ${f(mean(opn.map((r) => r.opinionA)))} / ${f(mean(opn.map((r) => r.opinionB)))} (n=${opn.length}). With learning OFF opinions stay 0 by construction.\n\n## Per-seed rows\n\n\`\`\`json\n${JSON.stringify(rows.map((r) => Object.fromEntries(Object.entries(r).map(([k, v]) => [k, typeof v === 'number' ? Math.round(v * 1000) / 1000 : v]))), null, 1)}\n\`\`\`\n\n## Reading these numbers honestly\n- Differences are from ${NSEEDS} seeds of a stochastic simulation; compare the paired diff with the sd before concluding anything.\n- Visitor-directed behaviour (approach/avoid ratios, distances) is the clearest learned signal: it is driven by the per-wallet opinion that only exists when learning is on.\n- Survival/feeding metrics move less: the prior policy is already competent in this ecology, so the bandit mostly fine-tunes it.\n`;
fs.mkdirSync(new URL('../results/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../results/learning-comparison.md', import.meta.url), md);
console.log(md.split('## Per-seed')[0]);
