// Read-only Git extraction: reproduce the reopened review against the delivered
// ca7a177 engine and generate an authentic pre-correction 99e50b1 snapshot.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const root = fileURLToPath(new URL('../../', import.meta.url));
const out = path.join(root, 'test/scratch/review-original');
const git = args => {
  const r = spawnSync('git', args, { cwd: root, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr); return r.stdout;
};
async function original(commit) {
  const dir = path.join(out, commit);
  for (const rel of git(['ls-tree', '-r', '--name-only', commit, 'server']).trim().split('\n')) {
    if (!rel.startsWith('server/src/') && rel !== 'server/package.json') continue;
    const target = path.join(dir, rel); fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, git(['show', `${commit}:${rel}`]));
  }
  const get = name => import(pathToFileURL(path.join(dir, `server/src/${name}.js`)).href);
  return { ...await get('world'), ...await get('config'), ...await get('actions'), ...await get('controller') };
}
const reopened = await original('ca7a177');
if (process.argv.includes('--check-regressions')) {
  const dir = path.join(out, 'ca7a177');
  fs.mkdirSync(path.join(dir, 'tests/fixtures'), { recursive: true });
  for (const rel of ['tests/review-regressions.test.js', 'tests/fixtures/accepted99e50b1-mb-decision.json.gz']) fs.copyFileSync(path.join(root, rel), path.join(dir, rel));
  const result = spawnSync(process.execPath, ['--test', '--test-reporter=tap', 'tests/review-regressions.test.js'], { cwd: dir, encoding: 'utf8', timeout: 60000 });
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stdout, /# pass 20\n# fail 16\n/);
  const evidence = path.join(root, 'artifacts/phase2a-client/review'); fs.mkdirSync(evidence, { recursive: true });
  fs.writeFileSync(path.join(evidence, 'before.tap.gz'), gzipSync(Buffer.from(result.stdout + result.stderr), { level: 9, mtime: 0 }));
}
const starvation = [];
for (const mode of reopened.BRAIN_MODES) for (const reverse of [false, true]) {
  const w = reopened.World.create(reopened.deepMerge(reopened.DEFAULTS, { world: { brainMode: mode, initialSeedCount: 1 } })), c = w.creatures[0];
  Object.assign(c, { x: 20, y: 20, hunger: 85, energy: 75 }); w.tick = 100;
  w.tiles.fill(0); for (const k of ['trees', 'stones', 'shelters', 'fires', 'storms']) w[k] = [];
  w.rebuildBlocked(); c.places.food = [];
  const full = [{ id: 10, x: 21, y: 20, amount: 5 }, { id: 20, x: 31, y: 20, amount: 5 }];
  w.bushes = [...Array.from({ length: 9 }, (_, i) => ({ id: 100 + i, x: 23 + i % 3, y: 21 + Math.floor(i / 3), amount: 0 })), ...(reverse ? full.reverse() : full)];
  reopened.decide(w, c);
  starvation.push({ mode, reverse, selected: c.act.bush, source: c.act.decisionSource, remembered: c.places.food.map(m => m.id) });
  assert.equal(c.act.bush, reverse ? 20 : 10, 'The reported baseline failure must reproduce');
}
const accepted = await original('99e50b1c275b9422c14f279498b3e192b151992b');
const w = accepted.World.create(accepted.deepMerge(accepted.DEFAULTS, { world: { brainMode: 'mb-v1', initialSeedCount: 1 } })), c = w.creatures[0];
Object.assign(c, { x: 20, y: 20, hunger: 40, energy: 75 });
w.tiles.fill(0); for (const k of ['trees', 'stones', 'shelters', 'fires', 'storms']) w[k] = [];
w.rebuildBlocked(); c.places.food = []; w.bushes = [{ id: 10, x: 21, y: 20, amount: 5 }];
const f = Array(12).fill(0.3);
for (let i = 0; i < 100; i++) {
  const score = accepted.scoreCandidate(w, c, 'EAT', f, { target: w.bushes[0] });
  accepted.rewardAction(w, c, { type: 'EAT', brainMode: 'mb-v1', trace: score.trace, f, u: score.u, decisionSource: 'model' }, 2);
}
